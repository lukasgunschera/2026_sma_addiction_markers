create_project_structure <- function(folders) {
  results <- sapply(folders, function(f) {
    if (!dir.exists(f)) {
      dir.create(f, recursive = TRUE)
      message("Created: ", f)
    } else {
      message("Already exists: ", f)
    }
  })
}
